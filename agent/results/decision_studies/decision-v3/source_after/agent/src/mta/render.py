"""N10: readable report from the structured record."""
from __future__ import annotations

from .store import Store


def _cell(s) -> str:
    return str(s if s is not None else "—").replace("|", "/").replace("\n", " ")


def _short(locator: str) -> str:
    return locator.split(" ")[0].split(".")[-1] if "dialog-act" in locator else locator


def render_report(items: list[dict], store: Store, mode: str, notes: dict) -> str:
    prior = {i["id"]: i for i in store.prior_items()}
    cur = store.meeting(store.current)
    role = {p["participant_id"]: p["role"] for p in store.roster(store.current)}
    by_type = {t: [i for i in items if i["type"] == t] for t in ("abstract", "decisions", "problems", "actions")}

    def ev(it):
        return ", ".join(f"`{r['locator'].split(' ')[0].replace(store.current + '.', '')}`" for r in it["reference"]
                         if r["source_type"] == "dialogue")[:300] or "—"

    def owner(it):
        o = it.get("owner")
        return ", ".join(f"{p} ({role.get(p, '?')})" for p in o) if o else "—"

    out = [f"# Meeting record: {store.current}", "",
           f"_Generated by the meeting-to-action workflow (mode `{mode}`). "
           f"Evidence IDs are dialogue-act IDs of the transcript._", "", "## Summary"]
    out += [f"- {i['text']}" for i in by_type["abstract"]] or ["- (none)"]

    out += ["", "## Decisions", "", "| ID | Decision | Status | Evidence |", "|---|---|---|---|"]
    out += [f"| {i['id'].split('.')[-1]} | {_cell(i['text'])} | {i['status']} | {ev(i)} |" for i in by_type["decisions"]]
    out += ["", "## Problems", "", "| ID | Problem | Status | Evidence |", "|---|---|---|---|"]
    out += [f"| {i['id'].split('.')[-1]} | {_cell(i['text'])} | {i['status']} | {ev(i)} |" for i in by_type["problems"]]

    out += ["", "## Action items", "",
            "| ID | Action | Owner | Owner basis | Deadline | Deadline basis | Status | Change vs earlier | Evidence |",
            "|---|---|---|---|---|---|---|---|---|"]
    for i in by_type["actions"]:
        rel = "; ".join(f"{r['relation']} {r['id']}" for r in i["related_items"]) or "—"
        out.append(f"| {i['id'].split('.')[-1]} | {_cell(i['text'])} | {owner(i)} | {i['owner_basis']} | "
                   f"{_cell(i['deadline'])} | {i['deadline_basis']} | {i['status']} | {rel} | {ev(i)} |")

    changed = [i for i in items if i.get("related_items")]
    out += ["", "## Changes since earlier meetings", ""]
    if not changed:
        out.append("No item was linked to an earlier meeting.")
    for i in changed:
        for r in i["related_items"]:
            old = prior.get(r["id"], {})
            out += [f"- **{i['id'].split('.')[-1]}** {r['relation']} `{r['id']}`",
                    f"  - earlier: {old.get('text', '(not available)')}",
                    f"  - now: {i['text']}"]

    open_items = [i for i in by_type["actions"]
                  if i["owner_basis"] in ("ambiguous", "missing") or i["deadline_basis"] == "ambiguous"]
    out += ["", "## Needs human confirmation", "",
            "_Nobody could be asked during processing, so these were left unresolved rather than guessed._", ""]
    if not open_items:
        out.append("Nothing flagged.")
    for i in open_items:
        why = []
        if i["owner_basis"] in ("ambiguous", "missing"):
            why.append(f"owner {i['owner_basis']}")
        if i["deadline_basis"] == "ambiguous":
            why.append("deadline ambiguous")
        out.append(f"- {i['id'].split('.')[-1]}: {i['text']} ({', '.join(why)})")

    out += ["", "## Evidence", ""]
    seen = set()
    for i in items:
        for r in i["reference"]:
            if r["source_type"] != "dialogue" or r["locator"] in seen:
                continue
            seen.add(r["locator"])
            mid = r["locator"].split(".")[0]
            if store.da_exists(mid, r["locator"]):
                m = store.meeting(mid)
                a = m.acts[m.by_id[r["locator"]]]
                out.append(f"- `{r['locator']}` {a['attributes']['role']}({a['attributes']['participant']}): {a['text']}")
    out += ["", "## Run notes", ""] + [f"- {k}: {v}" for k, v in notes.items()]
    return "\n".join(out) + "\n"
